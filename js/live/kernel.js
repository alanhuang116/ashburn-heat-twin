const qoff = (q, N) => (q === 0 ? '' : `${q * N}u + `);

// solidity test of cell (kk, column at offset (ox, oy) from the thread's column) == flag[...] != 0 in the prototype
function solidExpr(cfg, kk, si, sj, ox, oy) {
  if (cfg.cacheNbr) return `(${kk} < kn${ox + 1}${oy + 1})`;
  return `(${kk} < i32(ktopc[${sj}*NX + ${si}]))`;
}

// ---- sections (each mirrors the corresponding block of gen_source) ----------------------------------------------

function secNeighbourCache(a, cfg) {
  if (!cfg.cacheNbr) return;
  a(`  let im = max(i - 1, 0); let ip = min(i + 1, NX - 1); let jm = max(j - 1, 0); let jp = min(j + 1, NY - 1);`);
  const xs = { '-1': 'im', '0': 'i', '1': 'ip' }, ys = { '-1': 'jm', '0': 'j', '1': 'jp' };
  for (const ox of [-1, 0, 1]) for (const oy of [-1, 0, 1]) {
    if (ox === 0 && oy === 0) { a(`  let kn11 = kg;`); continue; }
    a(`  let kn${ox + 1}${oy + 1} = i32(ktopc[${ys[oy]}*NX + ${xs[ox]}]);`);
  }
}

function secProfile(a) {
  a(`  var zagl = k - ktc;`);
  a(`  if (zagl < 0) {`);
  a(`    zagl = 0;`);
  a(`  }`);
  a(`  // inflow wind at this height (used for faces flagged inflow)`);
  a(`  let uI = P.prof[zagl].x;`);
  a(`  let vI = P.prof[zagl].y;`);
}

function secOutflowPrelude(a, N) {
  a(`  // outflow faces: non-equilibrium extrapolation with the density pinned to 1 (pressure outlet)`);
  a(`  var rn = 1.0; var uxn = 0.0; var uyn = 0.0; var uzn = 0.0;`);
  a(`  let onb = (i == 0 && P.inflow_w == 0) || (i == NX-1 && P.inflow_e == 0) || (j == 0 && P.inflow_s == 0) || (j == NY-1 && P.inflow_n == 0);`);
  a(`  if (onb) {`);
  a(`    rn = ` + C19.map((_, q) => `fA[${qoff(q, N)}nu]`).join(' + ') + ';');
  for (const [comp, nm] of [[0, 'uxn'], [1, 'uyn'], [2, 'uzn']]) {
    const terms = [];
    C19.forEach((c, q) => {
      if (c[comp] === 1) terms.push(`+fA[${qoff(q, N)}nu]`);
      else if (c[comp] === -1) terms.push(`-fA[${qoff(q, N)}nu]`);
    });
    a(`    ${nm} = (` + terms.join(' ').replace(/^\+/, '') + `)/rn;`);
  }
  a(`  }`);
  a(`  let usqn = uxn*uxn + uyn*uyn + uzn*uzn;`);
  // [live extension, P.oclip != 0] outlets do not let air in: the velocity of the reconstructed incoming populations
  // has its inward normal component clipped to zero (identical to the prototype wherever there is no backflow)
  a(`  var uxc = uxn; var uyc = uyn;`);
  a(`  if (P.oclip != 0) {`);
  a(`    if (i == 0 && P.inflow_w == 0 && uxc > 0.0) { uxc = 0.0; }`);
  a(`    if (i == NX-1 && P.inflow_e == 0 && uxc < 0.0) { uxc = 0.0; }`);
  a(`    if (j == 0 && P.inflow_s == 0 && uyc > 0.0) { uyc = 0.0; }`);
  a(`    if (j == NY-1 && P.inflow_n == 0 && uyc < 0.0) { uyc = 0.0; }`);
  a(`  }`);
  a(`  let usqc = uxc*uxc + uyc*uyc + uzn*uzn;`);
}

function inflowCond(cx, cy) {
  const t = [];
  if (cx === 1) t.push('(si < 0 && P.inflow_w != 0)');
  if (cx === -1) t.push('(si >= NX && P.inflow_e != 0)');
  if (cy === 1) t.push('(sj < 0 && P.inflow_s != 0)');
  if (cy === -1) t.push('(sj >= NY && P.inflow_n != 0)');
  return t.length ? t.join(' || ') : 'false';
}

function secStreamF(a, cfg, N) {
  C19.forEach(([cx, cy, cz], q) => {
    if (q === 0) { a(`  let f0 = fA[nu];`); return; }
    a(`  // q=${q} c=(${cx},${cy},${cz})`);
    a(`  var f${q}: f32;`);
    a(`  {`);
    a(`    let si = i - (${cx}); let sj = j - (${cy}); let sk = k - (${cz});`);
    a(`    let outx = (si < 0) || (si >= NX);`);
    a(`    let outy = (sj < 0) || (sj >= NY);`);
    a(`    if (sk >= NZ) {`);
    // free-slip lid: specular reflection of the population coming from above, mirrored pop from the same layer
    const m = MIRZ19[q];
    a(`      let ti = si; let tj = sj;`);
    a(`      if (ti < 0 || ti >= NX || tj < 0 || tj >= NY) {`);
    a(`        f${q} = fA[${qoff(m, N)}nu];`);
    a(`      } else {`);
    a(`        let t = (k*NY + tj)*NX + ti;`);
    a(`        if ${solidExpr(cfg, 'k', 'ti', 'tj', -cx, -cy)} {`);
    a(`          f${q} = fA[${qoff(m, N)}nu];`);
    a(`        } else {`);
    a(`          f${q} = fA[${qoff(m, N)}u32(t)];`);
    a(`        }`);
    a(`      }`);
    a(`    } else if (outx || outy) {`);
    // inflow or outflow
    const cu = [];
    if (cx) cu.push(`(${cx})*uI`);
    if (cy) cu.push(`(${cy})*vI`);
    a(`      if (${inflowCond(cx, cy)}) {`);
    a(`        let cu = ${cu.length ? cu.join('+') : '0.0'};`);
    a(`        f${q} = ${fmt(W19[q])}*(1.0 + 3.0*cu + 4.5*cu*cu - 1.5*(uI*uI+vI*vI));`);
    a(`      } else {`);
    const cun = [];
    if (cx) cun.push(`(${cx})*uxn`);
    if (cy) cun.push(`(${cy})*uyn`);
    if (cz) cun.push(`(${cz})*uzn`);
    a(`        let cu = ${cun.length ? cun.join('+') : '0.0'};`);
    const cuc = [];
    if (cx) cuc.push(`(${cx})*uxc`);
    if (cy) cuc.push(`(${cy})*uyc`);
    if (cz) cuc.push(`(${cz})*uzn`);
    a(`        if (P.oclip != 0) {`);
    a(`          let cuc = ${cuc.length ? cuc.join('+') : '0.0'};`);
    a(`          f${q} = fA[${qoff(q, N)}nu] + ${fmt(W19[q])}*((1.0 + 3.0*cuc + 4.5*cuc*cuc - 1.5*usqc) - rn*(1.0 + 3.0*cu + 4.5*cu*cu - 1.5*usqn));`);
    a(`        } else {`);
    a(`          f${q} = fA[${qoff(q, N)}nu] + ${fmt(W19[q])}*(1.0 - rn)*(1.0 + 3.0*cu + 4.5*cu*cu - 1.5*usqn);`);
    a(`        }`);
    a(`      }`);
    a(`    } else {`);
    a(`      let s = (sk*NY + sj)*NX + si;`);
    a(`      if ${solidExpr(cfg, 'sk', 'si', 'sj', -cx, -cy)} {`);
    a(`        f${q} = fA[${qoff(OPP19[q], N)}nu];`);
    a(`      } else {`);
    a(`        f${q} = fA[${qoff(q, N)}u32(s)];`);
    a(`      }`);
    a(`    }`);
    a(`  }`);
  });
}

function secStreamG(a, cfg, N, ind = '  ') {
  C7.forEach(([cx, cy, cz], q) => {
    if (q === 0) { a(`${ind}let g0 = gA[nu];`); return; }
    a(`${ind}var g${q}: f32;`);
    a(`${ind}{`);
    a(`${ind}  let si = i - (${cx}); let sj = j - (${cy}); let sk = k - (${cz});`);
    a(`${ind}  if (sk >= NZ) {`);
    a(`${ind}    g${q} = gA[${qoff(q, N)}nu];`);      // zero-gradient top for the scalar
    a(`${ind}  } else if (si < 0 || si >= NX || sj < 0 || sj >= NY) {`);
    a(`${ind}    if (${inflowCond(cx, cy)}) {`);
    a(`${ind}      g${q} = 0.0;`);
    a(`${ind}    } else {`);
    a(`${ind}      g${q} = gA[${qoff(q, N)}nu];`);
    a(`${ind}    }`);
    a(`${ind}  } else {`);
    a(`${ind}    let s = (sk*NY + sj)*NX + si;`);
    a(`${ind}    if ${solidExpr(cfg, 'sk', 'si', 'sj', -cx, -cy)} {`);
    a(`${ind}      g${q} = gA[${qoff(OPP7[q], N)}nu];`);
    a(`${ind}    } else {`);
    a(`${ind}      g${q} = gA[${qoff(q, N)}u32(s)];`);
    a(`${ind}    }`);
    a(`${ind}  }`);
    a(`${ind}}`);
  });
}

function mom(comp) {
  const terms = [];
  C19.forEach((c, q) => {
    if (c[comp] === 1) terms.push(`f${q}`);
    else if (c[comp] === -1) terms.push(`-f${q}`);
  });
  return terms.map(t => (t.startsWith('-') ? t : '+' + t)).join(' ').replace(/^\+/, '');
}

function mom2(p, r) {
  const terms = [];
  C19.forEach((c, q) => {
    const v = c[p] * c[r];
    if (v === 1) terms.push(`+f${q}`);
    else if (v === -1) terms.push(`-f${q}`);
  });
  return terms.join(' ').replace(/^\+/, '');
}

function secMoments(a, second) {
  a(`  let rho = ` + C19.map((_, q) => `f${q}`).join(' + ') + ';');
  a(`  let jx = ${mom(0)};`);
  a(`  let jy = ${mom(1)};`);
  a(`  let jz = ${mom(2)};`);
  a(`  let th = ` + C7.map((_, q) => `g${q}`).join(' + ') + ';');
  if (!second) return;
  a(`  let Pxx = ${mom2(0, 0)};`);
  a(`  let Pyy = ${mom2(1, 1)};`);
  a(`  let Pzz = ${mom2(2, 2)};`);
  a(`  let Pxy = ${mom2(0, 1)};`);
  a(`  let Pxz = ${mom2(0, 2)};`);
  a(`  let Pyz = ${mom2(1, 2)};`);
}

function secForces(a) {
  a(`  var Fx = 0.0; var Fy = 0.0;`);
  a(`  var Fz = rho*P.gbeta*th;`);
  a(`  if (k == kg && kg == ktc) {`);
  a(`    let ux0 = jx/rho; let uy0 = jy/rho;`);
  a(`    let sp = sqrt(ux0*ux0 + uy0*uy0);`);
  a(`    let cd = bitcast<f32>(cv.z);`);
  a(`    Fx = -rho*cd*sp*ux0;`);
  a(`    Fy = -rho*cd*sp*uy0;`);
  a(`    // implicit-limited drag: never reverse the flow within a step`);
  a(`    let lim = 0.5*rho;`);
  a(`    if (cd*sp > 0.5) {`);
  a(`      Fx = -lim*ux0; Fy = -lim*uy0;`);
  a(`    }`);
  a(`  }`);
  a(`  // top sponge (absorbing layer standing in for the deeper convective boundary layer above the lid)`);
  a(`  var sg = 0.0;`);
  a(`  if (k >= NZ - P.nsp) {`);
  a(`    let aa = (f32(k - (NZ - P.nsp)) + 1.0)/f32(P.nsp);`);
  a(`    sg = P.sigmax*aa*aa;`);
  a(`    Fx += rho*sg*(uI - jx/rho);`);
  a(`    Fy += rho*sg*(vI - jy/rho);`);
  a(`    Fz += -rho*sg*(jz/rho);`);
  a(`  }`);
  a(`  let ux = (jx + 0.5*Fx)/rho;`);
  a(`  let uy = (jy + 0.5*Fy)/rho;`);
  a(`  let uz = (jz + 0.5*Fz)/rho;`);
}

function secRelax(a) {
  a(`  let usq = ux*ux + uy*uy + uz*uz;`);
  a(`  let r3 = rho*(1.0/3.0);`);
  a(`  let Nxx = Pxx - r3 - rho*ux*ux;`);
  a(`  let Nyy = Pyy - r3 - rho*uy*uy;`);
  a(`  let Nzz = Pzz - r3 - rho*uz*uz;`);
  a(`  let Nxy = Pxy - rho*ux*uy;`);
  a(`  let Nxz = Pxz - rho*ux*uz;`);
  a(`  let Nyz = Pyz - rho*uy*uz;`);
  a(`  let Pn = sqrt(Nxx*Nxx + Nyy*Nyy + Nzz*Nzz + 2.0*(Nxy*Nxy + Nxz*Nxz + Nyz*Nyz));`);
  a(`  // background (K-profile) viscosity at this height above ground`);
  a(`  let kb = P.prof[zagl].z;`);
  a(`  var tb = P.tau0 + 3.0*P.momfac*kb;`);
  a(`  // viscous sponge next to outflow faces (damps reflections / spurious backflow)`);
  a(`  var dmin = 1000;`);
  a(`  if (P.inflow_w == 0 && i < dmin) { dmin = i; }`);
  a(`  if (P.inflow_e == 0 && NX-1-i < dmin) { dmin = NX-1-i; }`);
  a(`  if (P.inflow_s == 0 && j < dmin) { dmin = j; }`);
  a(`  if (P.inflow_n == 0 && NY-1-j < dmin) { dmin = NY-1-j; }`);
  a(`  if (dmin < P.nsw) {`);
  a(`    let rr = (f32(P.nsw) - f32(dmin))/f32(P.nsw);`);
  a(`    tb += 0.15*rr*rr;`);
  a(`  }`);
  a(`  let tau = 0.5*(tb + sqrt(tb*tb + P.cs2smag*Pn/rho));`);
  a(`  let nusgs = (tau - tb)*(1.0/3.0);`);
  a(`  let kap = nusgs/P.prt + kb + P.kfloor;`);
  a(`  let taug = 0.5 + 4.0*kap;`);
  a(`  let om = 1.0 - 1.0/tau;`);
  a(`  let fpre = 1.0 - 0.5/tau;`);
  a(`  let trN = (Nxx + Nyy + Nzz)*(1.0/3.0);`);
}

function secCollision(a, N) {
  C19.forEach(([cx, cy, cz], q) => {
    const cu = [];
    if (cx) cu.push(`(${cx})*ux`);
    if (cy) cu.push(`(${cy})*uy`);
    if (cz) cu.push(`(${cz})*uz`);
    const qn = [];
    [[0, 'xx'], [1, 'yy'], [2, 'zz']].forEach(([p, pn]) => { if (C19[q][p] !== 0) qn.push(`N${pn}`); });
    const cross = [];
    if (cx && cy) cross.push(`2.0*(${cx * cy})*Nxy`);
    if (cx && cz) cross.push(`2.0*(${cx * cz})*Nxz`);
    if (cy && cz) cross.push(`2.0*(${cy * cz})*Nyz`);
    const qnexpr = (qn.length || cross.length) ? [...qn, ...cross].join(' + ') : '0.0';
    const cF = [];
    if (cx) cF.push(`(${cx})*Fx`);
    if (cy) cF.push(`(${cy})*Fy`);
    if (cz) cF.push(`(${cz})*Fz`);
    const w = fmt(W19[q]);
    a(`  {`);
    a(`    let cu = ${cu.length ? cu.join('+') : '0.0'};`);
    a(`    let feq = ${w}*rho*(1.0 + 3.0*cu + 4.5*cu*cu - 1.5*usq);`);
    a(`    let fr = ${fmt(4.5 * W19[q])}*((${qnexpr}) - trN);`);
    a(`    let cF = ${cF.length ? cF.join('+') : '0.0'};`);
    a(`    let Fq = fpre*${w}*(3.0*(cF - (ux*Fx+uy*Fy+uz*Fz)) + 9.0*cu*cF);`);
    a(`    fB[${qoff(q, N)}nu] = feq + om*fr + Fq;`);
    a(`  }`);
  });
}

function secScalarCollision(a, N) {
  a(`  var S = 0.0;`);
  a(`  if (k == kg) {`);
  a(`    S = bitcast<f32>(cv.w)*P.srcscale;`);
  a(`  }`);
  a(`  let omg = 1.0/taug;`);
  C7.forEach(([cx, cy, cz], q) => {
    const cu = [];
    if (cx) cu.push(`(${cx})*ux`);
    if (cy) cu.push(`(${cy})*uy`);
    if (cz) cu.push(`(${cz})*uz`);
    const w = fmt(W7[q]);
    a(`  {`);
    a(`    let geq = ${w}*th*(1.0 + 4.0*(${cu.length ? cu.join('+') : '0.0'}));`);
    a(`    gB[${qoff(q, N)}nu] = (g${q} + omg*(geq - g${q}) + ${w}*S)*(1.0 - sg);`);
    a(`  }`);
  });
}

function cellIndexFromGid(a, cfg) {
  a(`  let n = i32(gid.x + gid.y * ${cfg.strideY}u);`);
}

