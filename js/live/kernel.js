/** the fused step. cfg: { nx, ny, nz, wg, strideY, cacheNbr, out: 'none' | 'out' | 'acc' } */
export function genStepWGSL(cfg) {
  const N = cfg.nx * cfg.ny * cfg.nz;
  const out = cfg.out || 'none';
  const L = header(cfg, out === 'none' ? BINDINGS.step : BINDINGS.stepDbg);
  const a = s => L.push(s);
  a(`@compute @workgroup_size(${cfg.wg})`);
  a(`fn main(@builtin(global_invocation_id) gid: vec3<u32>) {`);
  cellIndexFromGid(a, cfg);
  a(`  if (n >= N) {`);
  a(`    return;`);
  a(`  }`);
  a(`  let i = n % NX;`);
  a(`  let j = (n / NX) % NY;`);
  a(`  let k = n / NXY;`);
  a(`  let col = j*NX + i;`);
  a(`  let cv = colv[col];`);
  a(`  let ktc = i32(cv.x);`);
  a(`  let kg = i32(cv.y);`);
  a(`  if (k < kg) {`);           // flag[n] != 0
  a(`    return;`);
  a(`  }`);
  a(`  let nu = u32(n);`);
  secProfile(a);
  secNeighbourCache(a, cfg);
  secOutflowPrelude(a, N);
  secStreamF(a, cfg, N);
  secStreamG(a, cfg, N);
  secMoments(a, true);
  secForces(a);
  secRelax(a);
  secCollision(a, N);
  secScalarCollision(a, N);
  if (out === 'out') a(`  dbg[nu] = vec4<f32>(th, ux, uy, uz);`);
  if (out === 'acc') a(`  dbg[nu] = dbg[nu] + vec4<f32>(th, ux, uy, uz);`);
  a(`}`);
  return L.join('\n');
}

/** near-surface extraction: the moments the next step would compute (pre-collision theta and the force-corrected
 *  velocity) in the first fluid cell above terrain or roof of every column; written north-up, u/v in m/s. */
export function genSurfWGSL(cfg) {
  const N = cfg.nx * cfg.ny * cfg.nz;
  const L = header(cfg, BINDINGS.surf);
  const a = s => L.push(s);
  a(`@compute @workgroup_size(${cfg.wg})`);
  a(`fn main(@builtin(global_invocation_id) gid: vec3<u32>) {`);
  a(`  let c = i32(gid.x);`);
  a(`  if (c >= NXY) {`);
  a(`    return;`);
  a(`  }`);
  a(`  let i = c % NX;`);
  a(`  let j = c / NX;`);
  a(`  let col = c;`);
  a(`  let cv = colv[col];`);
  a(`  let ktc = i32(cv.x);`);
  a(`  let kg = i32(cv.y);`);
  a(`  let k = kg;`);
  a(`  let o = u32((NY - 1 - j)*NX + i);`);
  a(`  if (k >= NZ) {`);
  a(`    sout[o] = 0.0; sout[u32(NXY) + o] = 0.0; sout[2u*u32(NXY) + o] = 0.0;`);
  a(`    return;`);
  a(`  }`);
  a(`  let n = (k*NY + j)*NX + i;`);
  a(`  let nu = u32(n);`);
  secProfile(a);
  secNeighbourCache(a, cfg);
  secOutflowPrelude(a, N);
  secStreamF(a, cfg, N);
  secStreamG(a, cfg, N);
  secMoments(a, false);
  secForces(a);
  a(`  sout[o] = th;`);
  a(`  sout[u32(NXY) + o] = ux*R.conv;`);
  a(`  sout[2u*u32(NXY) + o] = uy*R.conv;`);
  a(`}`);
  return L.join('\n');
}

/** theta volume of the lowest nzv levels, north-up [k][row][col], quantized theta*volscale to u8, 4 cells per u32
 *  (little-endian, so the bytes are in linear order); also the max theta (atomic, f32 bits) into stat[0]. */
export function genVolWGSL(cfg) {
  const N = cfg.nx * cfg.ny * cfg.nz;
  const nvol = cfg.nzv * cfg.nx * cfg.ny;
  const nw = Math.ceil(nvol / 4);
  const L = header({ ...cfg, cacheNbr: false }, BINDINGS.vol);
  const a = s => L.push(s);
  a(`const NVOL: i32 = ${nvol};`);
  a(`const NVOLW: i32 = ${nw};`);
  a(`var<workgroup> wmax: atomic<u32>;`);
  a(`@compute @workgroup_size(${cfg.wg})`);
  a(`fn main(@builtin(global_invocation_id) gid: vec3<u32>, @builtin(local_invocation_index) li: u32) {`);
  a(`  if (li == 0u) { atomicStore(&wmax, 0u); }`);
  a(`  workgroupBarrier();`);
  a(`  let t = i32(gid.x + gid.y * ${cfg.strideYVol}u);`);
  a(`  var packed = 0u;`);
  a(`  var tmax = 0.0;`);
  a(`  if (t < NVOLW) {`);
  a(`    for (var e = 0; e < 4; e++) {`);
  a(`      let p = 4*t + e;`);
  a(`      if (p < NVOL) {`);
  a(`        let k = p / NXY;`);
  a(`        let rem = p % NXY;`);
  a(`        let i = rem % NX;`);
  a(`        let j = NY - 1 - rem / NX;`);
  a(`        let kg = i32(ktopc[j*NX + i]);`);
  a(`        var th = 0.0;`);
  a(`        if (k >= kg) {`);
  a(`          let nu = u32((k*NY + j)*NX + i);`);
  const LL = [];
  secStreamG(s => LL.push(s), { cacheNbr: false }, N, '          ');
  LL.forEach(s => a(s));
  a(`          th = ` + C7.map((_, q) => `g${q}`).join(' + ') + ';');
  a(`        }`);
  a(`        let qv = u32(clamp(round(th*R.volscale), 0.0, 255.0));`);
  a(`        packed = packed | (qv << (8u*u32(e)));`);
  a(`        tmax = max(tmax, th);`);
  a(`      }`);
  a(`    }`);
  a(`    vout[t] = packed;`);
  a(`    atomicMax(&wmax, bitcast<u32>(max(tmax, 0.0)));`);
  a(`  }`);
  a(`  workgroupBarrier();`);
  a(`  if (li == 0u) { atomicMax(&stat[0], atomicLoad(&wmax)); }`);
  a(`}`);
  return L.join('\n');
}

/** initial state, as lbm3d.Sim.__init__: equilibrium with the inflow profile at the local height above terrain
 *  (rho = 1, uz = 0) in every cell, written to both population buffers. */
export function genInitWGSL(cfg) {
  const N = cfg.nx * cfg.ny * cfg.nz;
  const L = header(cfg, BINDINGS.init);
  const a = s => L.push(s);
  a(`@compute @workgroup_size(${cfg.wg})`);
  a(`fn main(@builtin(global_invocation_id) gid: vec3<u32>) {`);
  cellIndexFromGid(a, cfg);
  a(`  if (n >= N) {`);
  a(`    return;`);
  a(`  }`);
  a(`  let i = n % NX;`);
  a(`  let j = (n / NX) % NY;`);
  a(`  let k = n / NXY;`);
  a(`  let ktc = i32(colv[j*NX + i].x);`);
  a(`  let zagl = clamp(k - ktc, 0, NZ - 1);`);
  a(`  let U = P.prof[zagl].x;`);
  a(`  let V = P.prof[zagl].y;`);
  a(`  let usq = U*U + V*V;`);
  a(`  let nu = u32(n);`);
  C19.forEach(([cx, cy], q) => {
    a(`  {`);
    a(`    let cu = (${cx}.0)*U + (${cy}.0)*V;`);
    a(`    let fq = ${fmt(W19[q])}*(1.0 + 3.0*cu + 4.5*cu*cu - 1.5*usq);`);
    a(`    f0w[${qoff(q, N)}nu] = fq;`);
    a(`    f1w[${qoff(q, N)}nu] = fq;`);
    a(`  }`);
  });
  a(`}`);
  return L.join('\n');
}

/** cells that turned from solid to fluid after a geometry change (a removed campus at fine dx): rest equilibrium
 *  (rho = 1, u = 0) and theta = 0 in the current population buffers. */
export function genReinitWGSL(cfg) {
  const N = cfg.nx * cfg.ny * cfg.nz;
  const L = header(cfg, BINDINGS.reinit);
  const a = s => L.push(s);
  a(`@compute @workgroup_size(${cfg.wg})`);
  a(`fn main(@builtin(global_invocation_id) gid: vec3<u32>) {`);
  a(`  let c = i32(gid.x);`);
  a(`  if (c >= NXY) {`);
  a(`    return;`);
  a(`  }`);
  a(`  let k1 = min(i32(oldk[c]), NZ);`);
  a(`  for (var k = i32(ktopc[c]); k < k1; k++) {`);
  a(`    let nu = u32(k*NXY + c);`);
  C19.forEach((_, q) => a(`    f0w[${qoff(q, N)}nu] = ${fmt(W19[q])};`));
  C7.forEach((_, q) => a(`    gw[${qoff(q, N)}nu] = 0.0;`));
  a(`  }`);
  a(`}`);
  return L.join('\n');
}

/** diagnostics over all fluid cells of the stored (post-collision) state: per-workgroup partial sums of
 *  (theta, kinetic energy 0.5|j|^2/rho, rho - 1, fluid cell count), max theta (stat[0]) and the number of cells with a
 *  non-finite rho or theta (stat[1], tested on the bit pattern because WGSL may assume finite math), max |j|/rho (stat[2]). */
export function genStatsWGSL(cfg) {
  const N = cfg.nx * cfg.ny * cfg.nz;
  const L = header(cfg, BINDINGS.stats);
  const a = s => L.push(s);
  a(`var<workgroup> red: array<vec4<f32>, ${cfg.wg}>;`);
  a(`var<workgroup> wmax: atomic<u32>;`);
  a(`var<workgroup> wumax: atomic<u32>;`);
  a(`@compute @workgroup_size(${cfg.wg})`);
  a(`fn main(@builtin(global_invocation_id) gid: vec3<u32>, @builtin(local_invocation_index) li: u32, @builtin(workgroup_id) wid: vec3<u32>, @builtin(num_workgroups) nwg: vec3<u32>) {`);
  a(`  if (li == 0u) { atomicStore(&wmax, 0u); atomicStore(&wumax, 0u); }`);
  cellIndexFromGid(a, cfg);
  a(`  var acc = vec4<f32>(0.0);`);
  a(`  var tmax = 0.0;`);
  a(`  var umax = 0.0;`);
  a(`  if (n < N) {`);
  a(`    let i = n % NX;`);
  a(`    let j = (n / NX) % NY;`);
  a(`    let k = n / NXY;`);
  a(`    if (k >= i32(ktopc[j*NX + i])) {`);
  a(`      let nu = u32(n);`);
  a(`      let rho = ` + C19.map((_, q) => `fA[${qoff(q, N)}nu]`).join(' + ') + ';');
  for (const [comp, nm] of [[0, 'jx'], [1, 'jy'], [2, 'jz']]) {
    const t = [];
    C19.forEach((c, q) => { if (c[comp] === 1) t.push(`+fA[${qoff(q, N)}nu]`); else if (c[comp] === -1) t.push(`-fA[${qoff(q, N)}nu]`); });
    a(`      let ${nm} = ${t.join(' ').replace(/^\+/, '')};`);
  }
  a(`      let th = ` + C7.map((_, q) => `gA[${qoff(q, N)}nu]`).join(' + ') + ';');
  a(`      let br = bitcast<u32>(rho) & 0x7f800000u;`);
  a(`      let bt = bitcast<u32>(th) & 0x7f800000u;`);
  a(`      if (br == 0x7f800000u || bt == 0x7f800000u) {`);
  a(`        atomicAdd(&stat[1], 1u);`);
  a(`      } else {`);
  a(`        acc = vec4<f32>(th, 0.5*(jx*jx + jy*jy + jz*jz)/rho, rho - 1.0, 1.0);`);
  a(`        tmax = max(th, 0.0);`);
  a(`        umax = sqrt(jx*jx + jy*jy + jz*jz)/rho;`);
  a(`      }`);
  a(`    }`);
  a(`  }`);
  a(`  red[li] = acc;`);
  a(`  workgroupBarrier();`);
  a(`  atomicMax(&wmax, bitcast<u32>(tmax));`);
  a(`  atomicMax(&wumax, bitcast<u32>(max(umax, 0.0)));`);
  a(`  for (var s = ${cfg.wg / 2}u; s > 0u; s = s >> 1u) {`);
  a(`    if (li < s) { red[li] = red[li] + red[li + s]; }`);
  a(`    workgroupBarrier();`);
  a(`  }`);
  a(`  if (li == 0u) {`);
  a(`    part[wid.x + wid.y * nwg.x] = red[0];`);
  a(`    atomicMax(&stat[0], atomicLoad(&wmax));`);
  a(`    atomicMax(&stat[2], atomicLoad(&wumax));`);
  a(`  }`);
  a(`}`);
  return L.join('\n');
}
